import React, { useState, useEffect } from 'react';
import {
  Lightbulb,
  TrendingDown,
  CheckCircle,
  AlertTriangle,
  ArrowRight,
  ShieldCheck,
  Target,
  Sparkles,
  HelpCircle
} from 'lucide-react';
import NotificationToast from '../components/NotificationToast';
import { suggestionsAPI } from '../services/api';

const Suggestions = () => {
  const [suggestions, setSuggestions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [selectedPriority, setSelectedPriority] = useState('All');
  const [toast, setToast] = useState(null);

  useEffect(() => {
    fetchSuggestions();
  }, []);

  const fetchSuggestions = async () => {
    setLoading(true);
    try {
      const data = await suggestionsAPI.getAll();
      setSuggestions(data || []);
    } catch (err) {
      setToast({
        type: 'error',
        title: 'Failed to load suggestions',
        message: err.message,
      });
    } finally {
      setLoading(false);
    }
  };

  const filteredSuggestions = suggestions.filter((s) => {
    if (selectedPriority === 'All') return true;
    return s.priority === selectedPriority;
  });

  const totalPotentialSavings = suggestions.reduce(
    (acc, curr) => acc + (curr.potential_savings_kg || 0),
    0
  );

  const getPriorityBadge = (priority) => {
    switch (priority) {
      case 'High':
        return <span className="badge badge-danger">High Priority</span>;
      case 'Medium':
        return <span className="badge badge-warning">Medium Priority</span>;
      case 'Low':
        return <span className="badge badge-info">Long-Term Impact</span>;
      default:
        return <span className="badge badge-secondary">{priority}</span>;
    }
  };

  return (
    <div className="page-container">
      <NotificationToast toast={toast} onClose={() => setToast(null)} />

      {/* Header Banner */}
      <div
        style={{
          background: 'linear-gradient(135deg, #15803D 0%, #065F46 100%)',
          borderRadius: '16px',
          padding: '24px 28px',
          color: '#FFFFFF',
          marginBottom: '24px',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          flexWrap: 'wrap',
          gap: '16px',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: '16px' }}>
          <div
            style={{
              width: '48px',
              height: '48px',
              borderRadius: '12px',
              backgroundColor: 'rgba(255, 255, 255, 0.2)',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              backdropFilter: 'blur(4px)',
            }}
          >
            <Lightbulb size={26} color="#FFFFFF" />
          </div>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <h2 style={{ fontSize: '1.25rem', fontWeight: '800', letterSpacing: '-0.01em', margin: 0 }}>
                Intelligent Waste Reduction Suggestions
              </h2>
              <span
                style={{
                  backgroundColor: '#DCFCE7',
                  color: '#15803D',
                  fontSize: '0.7rem',
                  fontWeight: '700',
                  padding: '2px 8px',
                  borderRadius: '9999px',
                }}
              >
                Rule-Based Engine
              </span>
            </div>
            <p style={{ fontSize: '0.85rem', color: '#DCFCE7', margin: '4px 0 0', maxWidth: '640px' }}>
              Actionable kitchen optimization strategies automatically generated by analyzing actual database waste ratios, high-frequency leftover items, and service shifts.
            </p>
          </div>
        </div>

        {/* Potential Savings Pill */}
        <div
          style={{
            backgroundColor: 'rgba(255, 255, 255, 0.15)',
            border: '1px solid rgba(255, 255, 255, 0.25)',
            borderRadius: '12px',
            padding: '12px 18px',
            textAlign: 'right',
          }}
        >
          <div style={{ fontSize: '0.72rem', color: '#DCFCE7', fontWeight: '600', textTransform: 'uppercase' }}>
            Potential Weekly Waste Cut
          </div>
          <div style={{ fontSize: '1.45rem', fontWeight: '800', color: '#FFFFFF' }}>
            ~{totalPotentialSavings.toFixed(0)} <span style={{ fontSize: '0.85rem' }}>kg</span>
          </div>
        </div>
      </div>

      {/* Priority Filter Bar */}
      <div
        style={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          flexWrap: 'wrap',
          gap: '12px',
          marginBottom: '20px',
        }}
      >
        <div style={{ display: 'flex', gap: '8px' }}>
          {['All', 'High', 'Medium', 'Low'].map((p) => (
            <button
              key={p}
              onClick={() => setSelectedPriority(p)}
              className={`btn btn-sm ${selectedPriority === p ? 'btn-primary' : 'btn-secondary'}`}
            >
              {p === 'All' ? 'All Suggestions' : `${p} Priority`}
            </button>
          ))}
        </div>

        <div style={{ fontSize: '0.8rem', color: '#64748B' }}>
          Showing <strong>{filteredSuggestions.length}</strong> rule-derived operational recommendations
        </div>
      </div>

      {/* Suggestion Cards Grid */}
      {loading ? (
        <div style={{ textAlign: 'center', padding: '60px 0' }}>
          <div style={{ width: '32px', height: '32px', border: '3px solid #E2E8F0', borderTopColor: '#15803D', borderRadius: '50%', animation: 'spin 0.8s linear infinite', margin: '0 auto 10px' }} />
          <span style={{ fontSize: '0.85rem', color: '#64748B' }}>Analyzing kitchen waste records...</span>
        </div>
      ) : filteredSuggestions.length > 0 ? (
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(360px, 1fr))', gap: '20px' }}>
          {filteredSuggestions.map((sug) => (
            <div
              key={sug.id}
              className="card"
              style={{
                display: 'flex',
                flexDirection: 'column',
                justifyContent: 'space-between',
                borderLeft: `4px solid ${sug.priority === 'High' ? '#EF4444' : sug.priority === 'Medium' ? '#F97316' : '#3B82F6'}`,
              }}
            >
              <div>
                <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '10px' }}>
                  <span style={{ fontSize: '0.75rem', fontWeight: '700', color: '#64748B', textTransform: 'uppercase' }}>
                    {sug.category}
                  </span>
                  {getPriorityBadge(sug.priority)}
                </div>

                <h3 style={{ fontSize: '1.05rem', fontWeight: '800', color: '#0F172A', marginBottom: '8px', lineHeight: 1.3 }}>
                  {sug.title}
                </h3>

                {/* Observation Box */}
                <div
                  style={{
                    backgroundColor: '#F8FAFC',
                    border: '1px solid #E2E8F0',
                    borderRadius: '8px',
                    padding: '10px 12px',
                    marginBottom: '12px',
                    fontSize: '0.8rem',
                    color: '#475569',
                    lineHeight: 1.5,
                  }}
                >
                  <strong style={{ color: '#0F172A' }}>Data Observation:</strong> {sug.observation}
                </div>

                {/* Recommendation Box */}
                <div
                  style={{
                    backgroundColor: '#F0FDF4',
                    border: '1px solid #BBF7D0',
                    borderRadius: '8px',
                    padding: '12px',
                    marginBottom: '16px',
                    fontSize: '0.85rem',
                    color: '#14532D',
                    lineHeight: 1.5,
                  }}
                >
                  <div style={{ display: 'flex', alignItems: 'center', gap: '6px', fontWeight: '700', marginBottom: '4px', color: '#15803D' }}>
                    <CheckCircle size={15} /> Practical Kitchen Action:
                  </div>
                  {sug.recommendation}
                </div>
              </div>

              {/* Card Footer Metrics */}
              <div
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  justifyContent: 'space-between',
                  paddingTop: '12px',
                  borderTop: '1px solid #F1F5F9',
                  fontSize: '0.78rem',
                }}
              >
                <div>
                  <span style={{ color: '#94A3B8' }}>Est. Savings:</span>{' '}
                  <strong style={{ color: '#15803D' }}>~{sug.potential_savings_kg} kg/service</strong>
                </div>
                <div>
                  <span style={{ color: '#64748B', fontWeight: '600' }}>{sug.impact}</span>
                </div>
              </div>
            </div>
          ))}
        </div>
      ) : (
        <div className="card" style={{ textAlign: 'center', padding: '48px 24px' }}>
          <p style={{ color: '#64748B', fontSize: '0.9rem' }}>
            No suggestions match the selected priority filter.
          </p>
        </div>
      )}

      {/* Campus Practical Implementation Best Practices */}
      <div className="card" style={{ marginTop: '28px' }}>
        <div className="card-header">
          <div>
            <h3 className="card-title">
              <ShieldCheck size={18} color="#15803D" /> EVS Canteen Waste Minimization Principles
            </h3>
            <p className="card-subtitle">
              Fundamental principles adopted from the Environmental Studies College Dining Framework
            </p>
          </div>
        </div>

        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(280px, 1fr))', gap: '16px', marginTop: '12px' }}>
          <div style={{ padding: '14px', borderRadius: '10px', backgroundColor: '#F8FAFC', border: '1px solid #E2E8F0' }}>
            <div style={{ fontWeight: '700', fontSize: '0.875rem', color: '#0F172A', marginBottom: '4px' }}>
              1. Source Reduction First
            </div>
            <p style={{ fontSize: '0.8rem', color: '#64748B', margin: 0, lineHeight: 1.5 }}>
              The highest environmental dividend comes from cooking only what is eaten through attendance synchronization and split-batch cooking.
            </p>
          </div>

          <div style={{ padding: '14px', borderRadius: '10px', backgroundColor: '#F8FAFC', border: '1px solid #E2E8F0' }}>
            <div style={{ fontWeight: '700', fontSize: '0.875rem', color: '#0F172A', marginBottom: '4px' }}>
              2. Mindful Dining Culture
            </div>
            <p style={{ fontSize: '0.8rem', color: '#64748B', margin: 0, lineHeight: 1.5 }}>
              Encourage students to take smaller initial portions with the reassurance that second helpings are freely available.
            </p>
          </div>

          <div style={{ padding: '14px', borderRadius: '10px', backgroundColor: '#F8FAFC', border: '1px solid #E2E8F0' }}>
            <div style={{ fontWeight: '700', fontSize: '0.875rem', color: '#0F172A', marginBottom: '4px' }}>
              3. Safe Surplus Redistribution
            </div>
            <p style={{ fontSize: '0.8rem', color: '#64748B', margin: 0, lineHeight: 1.5 }}>
              Edible surplus that cannot be served internally should be promptly transferred to verified local hunger relief volunteers within safe time limits.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
};

export default Suggestions;
